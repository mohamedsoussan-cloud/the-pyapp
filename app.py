@app.get("/api/state")
@login_required
def get_state():
    try:
        with engine.connect() as conn:
            rows = conn.execute(text("SELECT key,value FROM app_storage")).fetchall()
            rev = conn.execute(text("SELECT value FROM app_meta WHERE key='revision'")).scalar_one_or_none() or "0"
        result = {row[0]: row[1] for row in rows}
        result["__revision"] = int(rev)
        return jsonify(result)
    except SQLAlchemyError:
        app.logger.exception("Lecture de l'état impossible")
        return jsonify({"error": "Erreur de base de données"}), 500


@app.post("/api/state")
@login_required
def save_state():
    payload = request.get_json(silent=True)
    if not isinstance(payload, dict) or len(payload) > 5000:
        return jsonify({"ok": False, "error": "État invalide"}), 400
    expected_revision = payload.get("__revision")
    try:
        expected_revision = int(expected_revision)
    except (TypeError, ValueError):
        return jsonify({"ok": False, "error": "Version de données manquante. Rechargez l'application."}), 400
    clean_payload = {
        k: v for k, v in payload.items()
        if isinstance(k, str) and k not in ("__data_version", "__revision") and isinstance(v, str)
    }
    try:
        # Optimistic concurrency control: only one client can commit a snapshot
        # based on a given revision. Stale clients receive 409 instead of erasing
        # another user's more recent stock changes.
        with engine.begin() as conn:
            claimed = conn.execute(text("UPDATE app_meta SET value=:new WHERE key='revision' AND value=:expected"), {
                "new": str(expected_revision + 1), "expected": str(expected_revision)
            })
            if claimed.rowcount != 1:
                current = conn.execute(text("SELECT value FROM app_meta WHERE key='revision'")).scalar_one_or_none() or "0"
                return jsonify({"ok": False, "conflict": True, "revision": int(current), "error": "Le stock a été modifié par un autre utilisateur."}), 409
            current_keys = [r[0] for r in conn.execute(text("SELECT key FROM app_storage")).fetchall()]
            for old_key in current_keys:
                if old_key not in clean_payload:
                    conn.execute(text("DELETE FROM app_storage WHERE key=:k"), {"k": old_key})
            for key, value in clean_payload.items():
                conn.execute(text("""INSERT INTO app_storage(key,value,updated_at) VALUES(:k,:v,CURRENT_TIMESTAMP)
                    ON CONFLICT(key) DO UPDATE SET value=excluded.value, updated_at=CURRENT_TIMESTAMP"""), {"k": key, "v": value})
        return jsonify({"ok": True, "revision": expected_revision + 1})
    except SQLAlchemyError:
        app.logger.exception("Sauvegarde de l'état impossible")
        return jsonify({"ok": False, "error": "Erreur de base de données"}), 500


@app.post("/api/reset")
@login_required
def reset_state():
    if session.get("role") != "admin":
        return jsonify({"ok": False, "error": "Réservé à l'administrateur"}), 403
    try:
        with engine.begin() as conn:
            conn.execute(text("DELETE FROM app_storage"))
            current = int(conn.execute(text("SELECT value FROM app_meta WHERE key='revision'")).scalar_one_or_none() or "0")
            conn.execute(text("UPDATE app_meta SET value=:v WHERE key='revision'"), {"v": str(current + 1)})
        return jsonify({"ok": True, "revision": current + 1, "message": "Données métier réinitialisées."})
    except SQLAlchemyError:
        app.logger.exception("Réinitialisation impossible")
        return jsonify({"ok": False, "error": "Erreur de base de données"}), 500


